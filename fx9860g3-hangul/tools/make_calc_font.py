def rows_of(art):
    rows = art.split("/") if art else []
    rows = (rows + ["." * 5] * 7)[:7]
    w = max((len(r) for r in rows), default=5)
    off = 1 if w >= 4 else 2
    out = []
    for r in rows:
        v = 0
        for i, ch in enumerate(r):
            if ch == "#":
                v |= 0x20 >> (off + i)
        out.append(v)
    return out

lines = ["/* Generated by tools/make_calc_font.py -- do not edit. 5x7 Run-Mat system font, 6 px pitch, bit 5 = left pixel. */",
         '#include "calc_font.h"', "",
         "const unsigned char calc_font[128][7] = {"]
for code in range(128):
    art = ART.get(chr(code))
    r = rows_of(art) if art is not None else [0] * 7
    lines.append("  {" + ",".join("0x%02X" % v for v in r) + "},  /* %d %s */" % (code, repr(chr(code)) if 32 <= code < 127 else ""))
lines.append("};")
out = Path(__file__).resolve().parent.parent / "src" / "calc_font.c"
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote", out)
