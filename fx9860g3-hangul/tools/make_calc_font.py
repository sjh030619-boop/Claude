"""Generate src/calc_font.c: the 5x7 system font of the fx-9860G III Run-Mat screen (fixed pitch 6 px).

Glyph shapes come from real screens: the 128x64 screenshot that src/fakecalc_data.c was made from
(digits, + x / ( ) . E -) and the screenshots in the fx-9860GIII Software User's Guide v3.21 (stencil
images of Run-Mat screens: the other digits and letters).  g, y and the radical sign are drawn by hand
in the same style.  Run:  python3 tools/make_calc_font.py
Codes: ASCII for plain characters, plus 0x01 x, 0x02 /, 0x03 square, 0x04 pi, 0x05 sqrt, 0x06 small E,
0x07 small minus (used in "2.5E-03").
"""
