#!/usr/bin/env python3
"""Turn a screenshot of the calculator's screen into src/fakecalc_data.c.

  python3 tools/make_fakecalc.py screenshot.png

Expects the usual emulator/photo-export layout: every LCD pixel is a SxS block
(S = image width / 132), with a 1-pixel frame and a 1-pixel white margin around
the 128x64 area. The result is shown by the "0" key (the fake Run-Mat screen).
"""
import sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
im = Image.open(sys.argv[1]).convert("L")
W, H = im.size
s = W // 132
assert W == 132 * s and H == 68 * s, f"unexpected size {W}x{H} (want 132s x 68s)"
px = im.load()
off = 2 * s  # frame + margin

rows = []
bad = 0
for r in range(64):
    v = 0
    for c in range(128):
        dark = sum(px[off + s * c + i, off + s * r + j] < 128 for i in range(s) for j in range(s))
        if 0 < dark < s * s:
            bad += 1
        v = (v << 1) | (1 if dark * 2 >= s * s else 0)
    rows.append(v)
if bad:
    print(f"warning: {bad} pixel blocks were not uniform", file=sys.stderr)

lines = ["/* Generated by tools/make_fakecalc.py -- do not edit. 128x64, MSB = left pixel. */",
         '#include "fakecalc.h"', "", "const unsigned char fakecalc_bits[64][16] = {"]
for v in rows:
    b = v.to_bytes(16, "big")
    lines.append("  {" + ",".join(f"0x{x:02X}" for x in b) + "},")
lines.append("};")
(ROOT / "src" / "fakecalc_data.c").write_text("\n".join(lines) + "\n")
print("wrote src/fakecalc_data.c")
